import { Grid } from '../pixelgen.mjs';
function poodle(flame) {
  const g = new Grid(32, 32);
  // boosters
  g.rect(4, 14, 4, 7, 'p').rect(24, 14, 4, 7, 'p').rect(5, 14, 1, 7, 'o').rect(25, 14, 1, 7, 'o');
  g.rect(4, 20, 4, 1, 'q').rect(24, 20, 4, 1, 'q');
  // hind legs pompoms
  g.ellipse(9.5, 12.5, 2.6, 2.6, '6').ellipse(22.5, 12.5, 2.6, 2.6, '6');
  // hindquarters
  g.ellipse(16, 11.5, 7, 5.2, '6');
  // tail stem + pompom
  g.rect(15, 4, 2, 3, '7');
  g.ellipse(16, 3.6, 3.4, 3.2, '6');
  // shaved waist
  g.ellipse(16, 17, 4.2, 2.6, '7');
  // front leg pompoms
  g.ellipse(8.5, 22.5, 2.6, 2.6, '6').ellipse(23.5, 22.5, 2.6, 2.6, '6');
  // mane
  g.ellipse(16, 21.5, 7.6, 4.8, '6');
  // ears
  g.ellipse(10.8, 27, 2.3, 3.8, '6').ellipse(21.2, 27, 2.3, 3.8, '6');
  // head
  g.ellipse(16, 27.2, 4.4, 3.6, '6');
  // shading (light from top-left)
  for (const c of ['6']) g.shade(c, '5', 1, 1, 1);
  g.shade('7', '8', 1, 1, 1);
  // curl texture
  for (const [x, y] of [[12, 10], [19, 9], [14, 13], [18, 13], [12, 20], [19, 20], [16, 23], [10, 22], [22, 22], [9, 12], [23, 12], [15, 3], [11, 27], [21, 27]]) g.px(x, y, '5');
  for (const [x, y] of [[13, 9], [17, 11], [15, 20], [18, 22], [14, 2], [16, 26]]) g.px(x, y, '7');
  // bow + collar
  g.rect(13, 24, 6, 1, 'd').px(15, 23, 'd').px(16, 23, 'd').px(14, 25, 'd').px(17, 25, 'd').px(15, 24, 'e').px(16, 24, 'e');
  // face: eyes and nose
  g.px(14, 29, '0').px(17, 29, '0').px(15, 31, '0').px(16, 31, '0').px(15, 30, 'c').px(16, 30, 'c');
  // booster flames
  if (flame !== null) {
    const f = flame === 0 ? [['f', 21], ['g', 22], ['r', 23]] : [['f', 21], ['f', 22], ['g', 23], ['r', 24]];
    for (const [c, y] of f) { g.rect(5, y, 2, 1, c); g.rect(25, y, 2, 1, c); }
    g.px(5, 21, 'l').px(26, 21, 'l');
  }
  g.outline('0');
  return g;
}
